const {setup, assert} = require('./helpers.cjs');
const t = setup();
t.change('landing-url','https://example.com/page?foo=1#section');
t.change('utm-source','google');
t.change('utm-medium','cpc');
t.change('utm-campaign','launch');
const value = t.get('utm-result').value || t.get('utm-result').textContent;
const url = new URL(value.trim());
assert.equal(url.searchParams.get('foo'),'1');
assert.equal(url.hash,'#section');
assert.equal(url.searchParams.get('utm_source'),'google');
assert.equal(url.searchParams.get('utm_medium'),'cpc');
assert.equal(url.searchParams.get('utm_campaign'),'launch');
t.get('utm-download').click();
assert.equal(t.downloads.length,1,'CSV export');
const dynamic = t.w.document.querySelector('[data-mode="dynamic"]');
assert.ok(dynamic);dynamic.click();
const template = t.get('utm-tracking').value || t.get('utm-tracking').textContent;
assert.ok(template.includes('{lpurl}'),'Dynamic Google Ads tracking template');
t.finish();
console.log('PASS parameters, existing query and hash, CSV export and dynamic template');
